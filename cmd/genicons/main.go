// Command genicons builds web/vendor/icons.svg, a sprite of the Lucide icons
// listed in web/icons.txt. It downloads the pinned lucide-static package from
// the npm registry once, checks its integrity hash and keeps only the icons
// the panel uses. The result is committed; run it again after editing icons.txt:
//
//	go run ./cmd/genicons
package main

import (
	"archive/tar"
	"bufio"
	"bytes"
	"compress/gzip"
	"crypto/sha512"
	"encoding/base64"
	"fmt"
	"io"
	"net/http"
	"os"
	"regexp"
	"sort"
	"strings"
)

const (
	lucideVersion   = "1.65.0"
	lucideURL       = "https://registry.npmjs.org/lucide-static/-/lucide-static-" + lucideVersion + ".tgz"
	lucideIntegrity = "sha512-Mbahsp1MHXzBK2qQ+j+OpdwvPwOFYFBOe2pD1O5eI+XLRpbqPY2euz6vemAddXGevRvJ5n8D83ilUCrtxP07RQ=="
	listPath        = "web/icons.txt"
	spritePath      = "web/vendor/icons.svg"
)

var innerRE = regexp.MustCompile(`(?s)<svg[^>]*>(.*)</svg>`)

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "genicons:", err)
		os.Exit(1)
	}
}

func run() error {
	names, err := readList(listPath)
	if err != nil {
		return err
	}
	tgz, err := download(lucideURL)
	if err != nil {
		return err
	}
	sum := sha512.Sum512(tgz)
	if got := "sha512-" + base64.StdEncoding.EncodeToString(sum[:]); got != lucideIntegrity {
		return fmt.Errorf("integrity mismatch for lucide-static %s: got %s", lucideVersion, got)
	}
	icons, err := extract(tgz, names)
	if err != nil {
		return err
	}

	var b strings.Builder
	b.WriteString(`<svg xmlns="http://www.w3.org/2000/svg">` + "\n")
	b.WriteString("<!-- Lucide " + lucideVersion + " (ISC), generated by cmd/genicons from web/icons.txt -->\n")
	for _, n := range names {
		fmt.Fprintf(&b, `<symbol id="%s" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">%s</symbol>`+"\n", n, icons[n])
	}
	b.WriteString("</svg>\n")
	if err := os.WriteFile(spritePath, []byte(b.String()), 0o644); err != nil {
		return err
	}
	fmt.Printf("wrote %s with %d icons\n", spritePath, len(names))
	return nil
}

func readList(path string) ([]string, error) {
	f, err := os.Open(path)
	if err != nil {
		return nil, err
	}
	defer f.Close()
	seen := map[string]bool{}
	var names []string
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		n := strings.TrimSpace(sc.Text())
		if n == "" || strings.HasPrefix(n, "#") || seen[n] {
			continue
		}
		seen[n] = true
		names = append(names, n)
	}
	sort.Strings(names)
	return names, sc.Err()
}

func download(url string) ([]byte, error) {
	res, err := http.Get(url)
	if err != nil {
		return nil, err
	}
	defer res.Body.Close()
	if res.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("download %s: %s", url, res.Status)
	}
	return io.ReadAll(res.Body)
}

// extract returns the inner markup of each wanted icon.
func extract(tgz []byte, names []string) (map[string]string, error) {
	want := map[string]bool{}
	for _, n := range names {
		want[n] = true
	}
	zr, err := gzip.NewReader(bytes.NewReader(tgz))
	if err != nil {
		return nil, err
	}
	tr := tar.NewReader(zr)
	out := map[string]string{}
	for {
		h, err := tr.Next()
		if err == io.EOF {
			break
		}
		if err != nil {
			return nil, err
		}
		rest, ok := strings.CutPrefix(h.Name, "package/icons/")
		name, isSVG := strings.CutSuffix(rest, ".svg")
		if !ok || !isSVG || !want[name] {
			continue
		}
		raw, err := io.ReadAll(tr)
		if err != nil {
			return nil, err
		}
		m := innerRE.FindSubmatch(raw)
		if m == nil {
			return nil, fmt.Errorf("icon %s: no <svg> element", name)
		}
		lines := strings.Split(strings.TrimSpace(string(m[1])), "\n")
		for i := range lines {
			lines[i] = strings.TrimSpace(lines[i])
		}
		out[name] = strings.Join(lines, "")
	}
	for _, n := range names {
		if _, ok := out[n]; !ok {
			return nil, fmt.Errorf("icon %q not found in lucide-static %s", n, lucideVersion)
		}
	}
	return out, nil
}
